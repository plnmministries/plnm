const DICT: Record<Lang, Record<UiKey, string>> = { en, te, hi };

export function uiText(lang: Lang, key: UiKey, vars?: Record<string, string | number>) {
  let s = DICT[lang][key] || en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
